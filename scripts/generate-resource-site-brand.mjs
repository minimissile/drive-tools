import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

// Reuse the existing brand exports without introducing an image dependency or
// starting another desktop workspace. Run again after updating build/icon.ico.
const root = new URL("../", import.meta.url);
const ico = await readFile(new URL("build/icon.ico", root));
const svg = await readFile(new URL("src/assets/brand/panxu-mark.svg", root), "utf8");
const pngs = new Map();
for (let i = 0; i < ico.readUInt16LE(4); i++) {
  const entry = 6 + i * 16;
  const width = ico[entry] || 256;
  const height = ico[entry + 1] || 256;
  const length = ico.readUInt32LE(entry + 8);
  const offset = ico.readUInt32LE(entry + 12);
  const image = ico.subarray(offset, offset + length);
  if (width === height && image.subarray(0, 8).equals(Buffer.from("89504e470d0a1a0a", "hex")))
    pngs.set(width, image);
}
const png = pngs.get(256), small = pngs.get(32);
if (!png || !small) throw new Error("Brand ICO must contain 256px and 32px PNG exports.");
const header = Buffer.alloc(22);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(1, 4);
header[6] = header[7] = 32;
header.writeUInt16LE(1, 10);
header.writeUInt16LE(32, 12);
header.writeUInt32LE(small.length, 14);
header.writeUInt32LE(22, 18);
const favicon = Buffer.concat([header, small]);
const hash = (bytes) => createHash("sha256").update(bytes).digest("hex").slice(0, 16);
const output = new URL("cloudflare/resource-links/src/brand-assets.ts", root);
await writeFile(output, `// Generated by scripts/generate-resource-site-brand.mjs; do not edit by hand.\nexport const brandSvg = ${JSON.stringify(svg)};\nexport const brandPng = ${JSON.stringify(png.toString("base64"))};\nexport const faviconIco = ${JSON.stringify(favicon.toString("base64"))};\nexport const brandHashes = ${JSON.stringify({ svg: hash(svg), png: hash(png), ico: hash(favicon) })} as const;\n`);
console.log(`Updated ${fileURLToPath(output)} from the existing Panxu brand exports.`);
