/** Only an allowlisted style can add instructions to the system prompt. */
export function wechatRewriteInstruction(
  styleId: WechatRewriteStyleId = defaultWechatRewriteStyle,
) {
  const selected = wechatRewriteStyleSchema.parse(styleId);
  return `${commonInstruction}\n${styleInstructions[selected]}`;
}
